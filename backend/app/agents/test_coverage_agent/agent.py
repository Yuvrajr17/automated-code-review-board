
from app.core.agent_config import create_groq_client


def create_test_coverage_agent():

    client = create_groq_client()

    return client.as_agent(
        name="TestCoverageAgent",

        instructions="""
        You are the Test-Coverage Agent in an Automated Code Review Board.

        Your responsibilities are:

        1. Review the test-file analysis generated by Python tools.
        2. Identify whether test files were modified.
        3. Evaluate the extent of test changes.
        4. Highlight potential testing gaps based on the supplied results.
        5. Recommend additional tests where appropriate.

        IMPORTANT:
        - Python tools have already identified test files and analyzed
          their changes.
        - Use the supplied results as evidence.
        - Do not invent test files or test counts.
        - Do not claim that tests were executed.
        - If no test files were modified, clearly state that.

        Return a concise, structured report.
        """
    )
